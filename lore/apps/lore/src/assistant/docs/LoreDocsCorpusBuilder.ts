import type { CapabilityKey } from "@lore/core/schemas";

/**
 * Builds the assistant's docs corpus from `lore/docs/1-guides` (#Q3212): one
 * entry per `##` section of each guide, with the guide's title, the section's
 * heading, its URL on the docs site and a short body.
 *
 * Run by `scripts/generate-docs-corpus.ts`, which writes `docsCorpus.ts`, and
 * by `assistant-docs.spec.ts`, which refuses a committed corpus that differs
 * from what the guides say now. Pure: it takes the files, never reads disk.
 */
export class LoreDocsCorpusBuilder {
  /**
   * Where Lore's guides are read, as `loreDocsUrl` writes it.
   */
  protected readonly docsRoot = "https://alepha.dev/lore/docs";

  /**
   * How much of a section the corpus keeps: enough to answer a how-to, short
   * enough that five hits stay far under what `$ai` keeps of a result.
   */
  protected readonly bodyCap = 1200;

  /**
   * The capability each guide documents, by file name. A guide absent from
   * this table documents Core, which every project has. Filtering is by
   * capability, not rank: a screen a rank cannot reach is still documented.
   */
  protected readonly capabilityOf: Record<string, CapabilityKey> = {
    "3-quests.md": "work",
    "4-epics.md": "work",
    "5-releases.md": "work",
    "12-automations.md": "work",
    "7-folios.md": "knowledge",
    "8-attachments.md": "knowledge",
    "9-feedback.md": "support",
    "15-telemetry.md": "apps",
    "16-healthchecks.md": "apps",
    "17-deploying.md": "apps",
    "18-artifacts.md": "apps",
    "19-stacks.md": "apps",
    "20-estates.md": "apps",
    "21-cloudflare-token.md": "apps",
  };

  /**
   * Every section of every guide, guides in their numbered order.
   */
  public build(files: Array<{ name: string; content: string }>): DocsSection[] {
    return [...files]
      .sort((a, b) => this.order(a.name) - this.order(b.name))
      .flatMap((file) => this.sectionsOf(file.name, file.content));
  }

  /**
   * The corpus as the TypeScript module `docsCorpus.ts` holds.
   */
  public render(sections: DocsSection[]): string {
    return [
      "// Generated by `yarn w lore docs:corpus` from lore/docs/1-guides (#Q3212).",
      "// Do not edit: `assistant-docs.spec.ts` refuses a corpus that differs",
      "// from the guides.",
      "",
      'import type { DocsSection } from "./LoreDocsCorpusBuilder.ts";',
      "",
      `export const docsCorpus: DocsSection[] = ${JSON.stringify(sections, null, 2)};`,
      "",
    ].join("\n");
  }

  protected sectionsOf(name: string, content: string): DocsSection[] {
    const slug = `guides-${name.replace(/\.md$/, "").replace(/^\d+-/, "")}`;
    const url = `${this.docsRoot}/${slug}`;
    const lines = content.split("\n");
    const guide = (lines.find((line) => line.startsWith("# ")) ?? name)
      .replace(/^# /, "")
      .trim();
    const capability = this.capabilityOf[name];

    const sections: DocsSection[] = [];
    let heading: string | undefined;
    let body: string[] = [];
    let fenced = false;
    const flush = () => {
      const text = this.clean(body.join("\n"));
      if (text) {
        sections.push({
          guide,
          section: heading ?? guide,
          url: heading ? `${url}#${this.anchorOf(heading)}` : url,
          ...(capability ? { capability } : {}),
          text,
        });
      }
    };
    for (const line of lines) {
      if (line.startsWith("```")) fenced = !fenced;
      if (!fenced && line.startsWith("## ")) {
        flush();
        heading = line.replace(/^## /, "").trim();
        body = [];
      } else if (!line.startsWith("# ")) {
        body.push(line);
      }
    }
    flush();
    return sections;
  }

  /**
   * A heading's anchor as the docs site writes it: lower case, punctuation
   * dropped, spaces as dashes.
   */
  protected anchorOf(heading: string): string {
    return heading
      .toLowerCase()
      .replace(/`/g, "")
      .replace(/[^\p{L}\p{N}\s-]/gu, "")
      .trim()
      .replace(/\s+/g, "-");
  }

  /**
   * A section's body for the model: blank runs folded, capped.
   */
  protected clean(text: string): string {
    const folded = text.replace(/\n{3,}/g, "\n\n").trim();
    return folded.length > this.bodyCap
      ? `${folded.slice(0, this.bodyCap)}...`
      : folded;
  }

  protected order(name: string): number {
    return Number.parseInt(name, 10) || 0;
  }
}

/**
 * One section of one of Lore's guides.
 */
export interface DocsSection {
  guide: string;
  section: string;
  /**
   * Where it is read, on the docs site.
   */
  url: string;
  /**
   * The capability the guide documents; absent for Core.
   */
  capability?: CapabilityKey;
  text: string;
}

import { $inject, Alepha, AlephaError } from "alepha";
import { CryptoProvider } from "alepha/crypto";
import { DateTimeProvider } from "alepha/datetime";
import {
  $repository,
  SqlExpressionProvider,
  sql,
  type SQLLike,
} from "alepha/orm";
import type { UserAccountToken } from "alepha/security";

import { projectEvents } from "../entities/projectEvents.ts";
import type { ProjectEventFields } from "../schemas/projectEventFieldsSchema.ts";
import { JobKeyService } from "./JobKeyService.ts";
import { LoreDatabase } from "./LoreDatabase.ts";
import {
  ProjectEventCatalog,
  type ProjectEventFieldKind,
} from "./ProjectEventCatalog.ts";
import { ProjectEventDelivery } from "./ProjectEventDelivery.ts";

/**
 * Records project events (#Q3889). `emit` returns the statements that record
 * one event, and its delivery job when someone is subscribed (#Q3890); the
 * caller adds them to the guarded batch of the change that caused it
 * (`GuardedBatch`, usually through `SourceRepository`), so an event is
 * written with its change or not at all, then calls `committed`. Nothing
 * here writes on its own.
 */
export class ProjectEvents {
  /**
   * Fields every event carries: the project's title, the subject's title,
   * and the subject's path in Lore.
   */
  public static readonly COMMON: Record<string, ProjectEventFieldKind> = {
    project: "text",
    title: "text",
    url: "text",
  };
  /**
   * The most rows one nightly prune deletes. Sized from a week of real quest
   * activity in production (written on #Q3889): project Alepha went from
   * quest 3500 to 3909 in 6.2 days, about 460 creates a week, so with as many
   * accepts and a few holds about 1,000 quest events a week, and well under
   * 200 events a day across the instance. The bound keeps a margin of ten.
   */
  public static readonly PRUNE_LIMIT = 2_000;
  /**
   * How long an event is kept. It feeds delivery; it is not a page.
   */
  public static readonly RETENTION_DAYS = 30;

  protected readonly alepha = $inject(Alepha);
  protected readonly crypto = $inject(CryptoProvider);
  protected readonly dateTime = $inject(DateTimeProvider);
  protected readonly database = $inject(LoreDatabase);
  protected readonly sqlx = $inject(SqlExpressionProvider);
  protected readonly catalog = $inject(ProjectEventCatalog);
  protected readonly events = $repository(projectEvents);
  protected readonly delivery = $inject(ProjectEventDelivery);

  /**
   * The statements that record one event, for the caller's guarded batch.
   * `numbers` are fields computed in the same batch (an id generated by the
   * insert the event follows), declared `number` in the catalog.
   */
  public async emit(input: ProjectEventInput): Promise<ProjectEventEmit> {
    const definition = this.catalog.get(input.name);
    const kinds = { ...ProjectEvents.COMMON, ...definition.fields };
    for (const key of Object.keys(input.numbers ?? {}))
      if (kinds[key] !== "number")
        throw new AlephaError(
          `Computed field '${key}' of '${input.name}' must be declared a number`,
        );
    const fields = this.fields(kinds, input.fields);
    let encoded: SQLLike = sql`${JSON.stringify(fields)}`;
    for (const [key, expression] of Object.entries(input.numbers ?? {})) {
      if (!/^[A-Za-z0-9_]+$/.test(key))
        throw new AlephaError("Invalid computed event field");
      encoded = this.sqlx.jsonSet(
        encoded,
        [key],
        typeof expression === "string"
          ? sql.raw(expression)
          : expression.getSQL(),
      );
    }
    const now = this.database.timestamp(this.dateTime.nowISOString());
    const id = this.crypto.randomUUID();
    const jobId =
      input.jobId === null
        ? undefined
        : (input.jobId ?? (await this.callerJob()));
    const job = await this.delivery.prepare(
      input.projectId,
      input.name,
      id,
      fields,
    );
    return {
      id,
      statements: [
        sql`INSERT INTO project_events (id, project_id, name, subject_kind, subject_id, fields, actor_id, job_id, occurred_at)
          VALUES (${id}, ${input.projectId}, ${input.name}, ${definition.subject}, ${input.subjectId === undefined ? null : String(input.subjectId)}, ${encoded}, ${input.actorId ?? null}, ${jobId ?? null}, ${now})`,
        ...(job?.statements ?? []),
      ],
      committed: async () => {
        if (job) await this.delivery.dispatch(job.id);
      },
    };
  }

  /**
   * The host job whose key made the current request (#Q4227), if a job key
   * made it. Resolved here rather than injected: the key service reaches
   * the MCP scope, which most event sources never load.
   */
  protected async callerJob(): Promise<string | undefined> {
    const request = this.alepha.store.get("alepha.http.request") as
      | { user?: UserAccountToken }
      | undefined;
    if (!request?.user) return undefined;
    const key = await this.alepha
      .inject(JobKeyService)
      .scopeOf(request.user)
      .catch(() => undefined);
    return key?.jobId;
  }

  /**
   * Deletes events older than the retention, oldest first, at most
   * {@link PRUNE_LIMIT} rows per call. Run by the nightly tick.
   */
  public async prune(): Promise<number> {
    const cutoff = this.dateTime
      .now()
      .subtract(ProjectEvents.RETENTION_DAYS, "days")
      .toISOString();
    let pruned = 0;
    while (pruned < ProjectEvents.PRUNE_LIMIT) {
      const rows = await this.events.findMany({
        where: { occurredAt: { lt: cutoff } },
        orderBy: "occurredAt",
        columns: ["id"],
        limit: 100,
      });
      if (!rows.length) break;
      pruned += (
        await this.events.deleteMany({
          id: { inArray: rows.map((row) => row.id) },
        })
      ).length;
      if (rows.length < 100) break;
    }
    return pruned;
  }

  /**
   * Only declared fields, each of the kind declared. A value of the wrong
   * kind becomes null rather than failing the change it is recorded with.
   */
  protected fields(
    kinds: Record<string, ProjectEventFieldKind>,
    input: Record<string, unknown>,
  ): ProjectEventFields {
    const fields: ProjectEventFields = {};
    for (const [key, kind] of Object.entries(kinds)) {
      if (!Object.hasOwn(input, key)) continue;
      const value = input[key];
      if (value === null || value === undefined) fields[key] = null;
      else if (kind === "number")
        fields[key] =
          typeof value === "number" && Number.isFinite(value) ? value : null;
      else if (kind === "boolean")
        fields[key] = typeof value === "boolean" ? value : null;
      else
        fields[key] =
          typeof value === "string" ? this.truncate(value, 16_384) : null;
    }
    return fields;
  }

  protected truncate(value: string, bytes: number): string {
    const encoder = new TextEncoder();
    if (encoder.encode(value).byteLength <= bytes) return value;
    let end = Math.min(value.length, bytes);
    while (end > 0 && encoder.encode(value.slice(0, end)).byteLength > bytes)
      end--;
    return value.slice(0, end);
  }
}

export interface ProjectEventInput {
  projectId: number;
  name: string;
  /**
   * The subject's id: a per-project number for quests, epics, releases and
   * feedback, the row id for the rest.
   */
  subjectId?: string | number;
  fields: Record<string, unknown>;
  numbers?: Record<string, SQLLike>;
  /**
   * The account whose action caused it, when one did (#Q3916).
   */
  actorId?: string;
  /**
   * The host job that caused it (#Q4227). Absent, the job whose key made
   * the current request, if one did. `null`, no job: for an event the
   * current request did not cause, such as one recorded by work deferred
   * to its end (#Q4331).
   */
  jobId?: string | null;
}

/**
 * One emitted event: its id, the statements for the change's batch, and what
 * to call once that batch committed (the delivery job's dispatch).
 */
export interface ProjectEventEmit {
  id: string;
  statements: SQLLike[];
  committed: () => Promise<void>;
}

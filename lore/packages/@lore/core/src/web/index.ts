/**
 * The browser-safe half of `@lore/core`, the glue: projects, capabilities, ranks and permissions, notifications, audits, the resource registry and its link graph, search, the dashboard, reports, agent prompts and the web shell: its pages, atoms and
 * dictionaries.
 *
 * Registered by BOTH entries, `main.server.ts` and `main.browser.ts`: the
 * server renders and the browser hydrates from the same page registry, so a
 * page known to one side only renders on the server and 404s after hydration.
 *
 * It imports another package's `./api` or `./mcp` as `import type` only:
 * a runtime import would bundle that package's server into the browser.
 *
 * @module
 */
export const LoreCoreWeb = $module({
  name: "lore.core.web",
  // `AlephaReactAuth` explicitly: the sign-in, register and verification
  // pages need `ReactAuth`, and nothing on the page tree injects it any more
  // (the old `AppRouter` held an unused field that registered it, #E75).
  imports: [AlephaReactUi, AlephaCrypto, AlephaReactAuth],
  atoms: [
    currentProjectAtom,
    currentProjectMemberAtom,
    projectPromptsAtom,
    userProjectsAtom,
  ],
  register(alepha) {
    // Injected here rather than listed in `services`: a listed service is
    // tagged with this module, and injecting it anywhere then registers the
    // whole module, router included. This module's barrel is what every
    // component imports from, so a spec rendering one `AccountRouter` page,
    // or reading the dictionaries, would boot Lore's whole page tree.
    alepha.inject(I18n);
    // Core's own dashboard metric descriptors (#Q2656), as each module's are.
    alepha.inject(CoreDashboardMetrics);
    alepha.inject(ThemesProvider);
    // Read by `Layout` and `HeaderActions` on every page, so it exists before
    // the container locks whether or not the app registers anything on it.
    alepha.inject(ShellExtensionRegistry);
    // Filled by every module's shell at boot, read by the app's assistant.
    alepha.inject(AssistantSuggestionRegistry);
    // Core's boot work (the 401 redirect, the global head, the reports tab
    // and services), apart from its pages so the router holds pages only
    // (#Q3400).
    alepha.inject(CoreWebBoot);
    // Routers with `alepha.with`, not `alepha.inject`: it is the same
    // registration today, and it returns nothing the caller reads, so a
    // build list can declare a pure router without creating it (#Q3417).
    alepha.with(CoreRouter);
    alepha.with(AutomationRouter);
    // The account dialog and Lore's sections of it (#E140): no route, the
    // dialog is drawn by the layout's `DialogProvider`.
    alepha.with(AccountDialog);
    alepha.with(LoreAccountSections);

    // Lore's `quests.createdBy` cascades, so deleting an account also deletes
    // every quest it authored, including inside other people's projects. The
    // framework cannot know that; this fills the dialog's warning slot so the
    // consequences are stated before the click rather than discovered after
    // it, each module's line registered on `AccountDeletionRegistry`.
    alepha.store.set(accountDialogOptionsAtom, {
      pages: {
        security: { deleteWarning: createElement(AccountDeleteWarning) },
      },
    });

    // Dogfood locale-prefix routing: French gets `/fr/...` URLs, English (the
    // default) stays unprefixed. Source of truth is the URL, with hreflang
    // alternates emitted for SEO.
    alepha.inject(I18nProvider).options.routing = "prefix";
  },
});


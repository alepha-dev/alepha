import type { DictionaryEntry } from "alepha/react/i18n";

/**
 * English strings for every component in this package.
 *
 * ### Why it exists when the components already speak English
 *
 * Every component calls `tr("…", { default: "English" })`, and the default is
 * the last thing `tr()` tries: the active language first, then `fallbackLang`,
 * and only then the default. In an application whose `fallbackLang` is `fr` and
 * which spreads `uiFr` into its French catalogue, an English visitor's lookup
 * misses in `en`, finds the key in `fr`, and gets a French interface; the
 * English default is never reached. Spreading this record into the `en`
 * catalogue makes the first lookup hit:
 *
 * ```ts
 * export class AppI18n {
 *   en = $dictionary({
 *     lazy: async () => ({ default: { ...uiEn, ...myKeys } }),
 *   });
 *   fr = $dictionary({
 *     lazy: async () => ({ default: { ...uiFr, ...mesClés } }),
 *   });
 * }
 * ```
 *
 * Spread first so the application always wins on a key it also defines. An
 * application whose `fallbackLang` is `en` does not need it.
 *
 * ### Coverage
 *
 * The same keys as `uiFr`, and each value is the English default its component
 * passes, so spreading it changes nothing an English visitor saw before. Keys
 * interpolate with `$1`, `$2` … positionally, matching the `args` each call site
 * passes.
 */
